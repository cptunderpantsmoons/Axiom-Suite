// Package provenance provides a lightweight "Proof of Source / Proof of Human"
// service: cryptographically signing data with an attested source (human, model,
// etc.) and verifying it hasn't been synthetically altered or model-poisoned.
//
// A payload is bound to a signed Attestation (source + signer + content hash +
// timestamp). Verification recomputes the content hash and checks an Ed25519
// signature over a canonical form of the attestation, so any alteration or a
// different source key yields a failed verdict.
package provenance

import (
	"context"
	"crypto/ed25519"
	"crypto/rand"
	"crypto/sha256"
	"encoding/base64"
	"encoding/hex"
	"fmt"
	"time"
)

// Source is the attested origin of a piece of data.
type Source string

const (
	SourceHuman   Source = "human"   // entered/confirmed by a person
	SourceModel   Source = "model"   // generated by an AI model (synthetic)
	SourceUnknown Source = "unknown" // not yet classified
)

// Attestation is the signed, tamper-evident metadata bound to a payload.
type Attestation struct {
	Version     int               `json:"version"`
	SignerID    string            `json:"signer_id"`
	Source      Source            `json:"source"`
	ContentHash string            `json:"content_hash"` // SHA-256 hex of payload
	Timestamp   time.Time         `json:"timestamp"`
	Meta        map[string]string `json:"meta,omitempty"`
}

// Record is a signed Attestation plus its Ed25519 signature (base64).
type Record struct {
	Attestation Attestation `json:"attestation"`
	Signature   string      `json:"signature"`
}

// Verdict is the result of Verify.
type Verdict struct {
	Valid    bool   `json:"valid"`
	Source   Source `json:"source"`
	SignerID string `json:"signer_id"`
	Reason   string `json:"reason,omitempty"`
}

// Signer signs payloads with a given identity and key.
type Signer struct {
	id   string
	priv ed25519.PrivateKey
}

// NewSigner constructs a provenance signer.
func NewSigner(id string, priv ed25519.PrivateKey) *Signer {
	return &Signer{id: id, priv: priv}
}

// GenerateSigner creates a new signer with a fresh key pair and returns its
// public key (for distribution to verifiers).
func GenerateSigner(id string) (*Signer, ed25519.PublicKey, error) {
	pub, priv, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		return nil, nil, err
	}
	return NewSigner(id, priv), pub, nil
}

// SignerID returns the signer identity.
func (s *Signer) SignerID() string { return s.id }

// PublicKey returns the signer's public key.
func (s *Signer) PublicKey() ed25519.PublicKey {
	return s.priv.Public().(ed25519.PublicKey)
}

// PrivateKey returns the raw private key (for persistence).
func (s *Signer) PrivateKey() ed25519.PrivateKey { return s.priv }

// Sign binds `source` and metadata to `payload`, returning the signed Record.
// Only the fixed fields (version, signer, source, content hash, timestamp) are
// signed; Meta is advisory and not part of the signature.
func (s *Signer) Sign(ctx context.Context, source Source, payload []byte, meta map[string]string) (*Record, error) {
	att := Attestation{
		Version:     1,
		SignerID:    s.id,
		Source:      source,
		ContentHash: hex.EncodeToString(sumSHA256(payload)),
		Timestamp:   time.Now().UTC(),
		Meta:        meta,
	}
	sig := ed25519.Sign(s.priv, []byte(att.canonical()))
	return &Record{Attestation: att, Signature: base64.StdEncoding.EncodeToString(sig)}, nil
}

// Verify checks that `payload` matches a Record's attested content hash and that
// the signature is valid under `pub`. An attacker who rewrites the payload (or
// re-signs with the wrong key) yields Valid=false.
func Verify(pub ed25519.PublicKey, payload []byte, rec *Record) *Verdict {
	if rec == nil {
		return &Verdict{Reason: "nil record"}
	}
	if hex.EncodeToString(sumSHA256(payload)) != rec.Attestation.ContentHash {
		return &Verdict{Reason: "content hash mismatch"}
	}
	sig, err := base64.StdEncoding.DecodeString(rec.Signature)
	if err != nil || len(sig) != ed25519.SignatureSize {
		return &Verdict{Reason: "malformed signature"}
	}
	if !ed25519.Verify(pub, []byte(rec.Attestation.canonical()), sig) {
		return &Verdict{Reason: "signature mismatch"}
	}
	return &Verdict{
		Valid:    true,
		Source:   rec.Attestation.Source,
		SignerID: rec.Attestation.SignerID,
	}
}

// HumanProof reports whether a verified record attests human origin — the
// "Proof of Human" check for filtering synthetic/model content.
func (v *Verdict) HumanProof() bool { return v != nil && v.Valid && v.Source == SourceHuman }

// canonical builds the signed bytes for an attestation over fixed fields only.
func (a *Attestation) canonical() string {
	return fmt.Sprintf("helm-provenance|v%d|%s|%s|%s|%d",
		a.Version, a.SignerID, a.Source, a.ContentHash, a.Timestamp.UnixNano())
}

func sumSHA256(b []byte) []byte {
	h := sha256.Sum256(b)
	return h[:]
}